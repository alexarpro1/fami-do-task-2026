// ============================================
// INTERNATIONALIZATION (i18n) – Multi-Language Engine
// ============================================
// Sprachen: DE, GB, ES, TR, RU, RO. Kein Reload bei Sprachwechsel; Texte on-the-fly.

export type Language = "de" | "gb" | "es" | "tr" | "ru" | "ro"

export const LANGUAGE_OPTIONS: { code: Language; name: string; flag: string; dir: "ltr" | "rtl" }[] = [
  { code: "de", name: "Deutsch", flag: "🇩🇪", dir: "ltr" },
  { code: "gb", name: "English", flag: "🇬🇧", dir: "ltr" },
  { code: "es", name: "Español", flag: "🇪🇸", dir: "ltr" },
  { code: "tr", name: "Türkçe", flag: "🇹🇷", dir: "ltr" },
  { code: "ru", name: "Русский", flag: "🇷🇺", dir: "ltr" },
  { code: "ro", name: "Română", flag: "🇷🇴", dir: "ltr" },
]

export const LANG_STORAGE_KEY = "famiapp-language"

/** Normiert gespeicherte Sprachcodes (z. B. en→gb, fr→de) für Abwärtskompatibilität. */
export function normalizeStoredLanguage(lang: string | undefined): Language {
  if (!lang) return "de"
  const normalized = lang === "en" ? "gb" : lang === "fr" || lang === "ar" ? "de" : lang
  return LANGUAGE_OPTIONS.some((o) => o.code === normalized) ? (normalized as Language) : "de"
}

/** Liest die beim Start gespeicherte Sprache (localStorage oder aus famiapp-state). Default: de. */
export function initTranslations(): Language {
  if (typeof window === "undefined") return "de"
  try {
    const direct = localStorage.getItem(LANG_STORAGE_KEY)
    if (direct) return normalizeStoredLanguage(direct)
    const stateRaw = localStorage.getItem("famiapp-state")
    if (stateRaw) {
      const state = JSON.parse(stateRaw) as { settings?: { language?: string } }
      return normalizeStoredLanguage(state.settings?.language)
    }
  } catch {
    /* ignore */
  }
  return "de"
}

/**
 * Gibt den Text für einen Pfad (z. B. "nav.home", "game.start") in der angegebenen Sprache zurück.
 * Platzhalter: z. B. tasks.capture = "Schlage {count} Steine" → t("tasks.capture", lang, { count: 3 })
 */
export function t(
  path: string,
  langOrParams?: Language | Record<string, string | number>,
  params?: Record<string, string | number>,
): string {
  const lang: Language =
    typeof langOrParams === "string" && LANGUAGE_OPTIONS.some((o) => o.code === langOrParams)
      ? langOrParams
      : (initTranslations() as Language)
  const paramMap = typeof langOrParams === "object" && langOrParams !== null ? langOrParams : params ?? {}
  const dict = translations[lang] ?? translations.de
  const value = getValueByPath(dict as Record<string, unknown>, path)
  const str = typeof value === "string" ? value : path
  return replacePlaceholders(str, paramMap)
}

function getValueByPath(obj: Record<string, unknown>, path: string): unknown {
  const parts = path.split(".")
  let current: unknown = obj
  for (const part of parts) {
    if (current == null || typeof current !== "object") return undefined
    current = (current as Record<string, unknown>)[part]
  }
  return current
}

function replacePlaceholders(str: string, params: Record<string, string | number>): string {
  return str.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`))
}

/**
 * Durchsucht das DOM nach [data-i18n] und setzt innerText auf die Übersetzung.
 * Für sofortiges UI-Update ohne Reload (z. B. nach setLanguage).
 */
export function applyTranslations(lang: Language): void {
  if (typeof document === "undefined") return
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n")
    if (key) el.textContent = t(key, lang)
  })
}

